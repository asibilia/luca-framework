#!/usr/bin/env bun
/**
 * Builds the `/luca-pr-prep` skill's helper (#738):
 *
 *   bun packages/engine/scripts/build-pr-story.ts
 *
 * It bundles `src/story/pr-story-main.ts`, with Zod and the story schema
 * inside it, into one file: `skills/luca-pr-prep/scripts/pr-story.js`.
 * A skill runs from `~/.claude/skills/`, where no packages are installed,
 * so the helper can't import Zod. Bundling lets the skill check a story
 * with the very schema the engine and a review app use, not a copy.
 *
 * The bundle's first line names the hash of the source it was built from
 * (`sourceHash`). `pr-story-bundle.test.ts` fails when that no longer
 * matches, which means: run this script again and commit the result.
 */
import { createHash } from 'node:crypto'
import { join } from 'node:path'

const ENGINE_DIR = join(import.meta.dir, '..')

/** The folder whose non-test files are the bundle's source. */
export const STORY_SOURCE_DIR = join(ENGINE_DIR, 'src', 'story')

/** The bundle the skill ships. */
export const BUNDLE_FILE = join(
    ENGINE_DIR,
    'skills',
    'luca-pr-prep',
    'scripts',
    'pr-story.js'
)

/** What the bundle's first line starts with; the hash follows. */
export const HASH_LINE = '// source-sha256: '

/**
 * The hash of the bundle's source: every non-test file in `src/story/`,
 * by name, plus the Zod version it is built with.
 */
export const sourceHash = async (): Promise<string> => {
    const files = (
        await Array.fromAsync(
            new Bun.Glob('*.ts').scan({ cwd: STORY_SOURCE_DIR })
        )
    )
        .filter((file) => !file.endsWith('.test.ts'))
        .toSorted()
    const hash = createHash('sha256')
    for (const file of files) {
        hash.update(`${file}\n`)
        hash.update(await Bun.file(join(STORY_SOURCE_DIR, file)).text())
    }
    const zod = await Bun.file(
        join(ENGINE_DIR, '..', '..', 'node_modules', 'zod', 'package.json')
    ).json()
    hash.update(`zod@${String(zod.version)}\n`)
    return hash.digest('hex')
}

if (import.meta.main) {
    const built = await Bun.build({
        entrypoints: [join(STORY_SOURCE_DIR, 'pr-story-main.ts')],
        target: 'bun',
        minify: true,
    })
    const [output] = built.outputs
    if (!built.success || output === undefined) {
        console.error(built.logs.join('\n'))
        process.exit(1)
    }
    const code = (await output.text()).replace(/^#!.*\n/, '')
    await Bun.write(
        BUNDLE_FILE,
        [
            '#!/usr/bin/env bun',
            `${HASH_LINE}${await sourceHash()}`,
            '// Generated by packages/engine/scripts/build-pr-story.ts from packages/engine/src/story/. Do not edit.',
            code,
        ].join('\n')
    )
    console.log(`Wrote ${BUNDLE_FILE} (${Bun.file(BUNDLE_FILE).size} bytes)`)
}
