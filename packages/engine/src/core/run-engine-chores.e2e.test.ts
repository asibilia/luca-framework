import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterEach, beforeEach, describe, expect, test } from 'bun:test'
import { z } from 'zod'

import type { JournalRecord } from '../journal/journal-record'
import {
    createPracticeRepo,
    git,
    happyTurns,
    IMPLEMENTER_RESULT,
    PRACTICE_ENGINE_CONFIG,
    TEST_WRITER_RESULT,
} from '../testing/practice-repo'

/**
 * Seam 2: one ticket, end to end, on the practice repo, with the two owner
 * chores the engine does itself (#618): a writer's `file_modes`, applied
 * before the commit, and the repo's named `generators`, run before the
 * gates as a `generate` check.
 */

/** A generator that rebuilds the committed README. */
const GEN_README = `await Bun.write('README.md', '# Practice\\n\\nGenerated by the readme generator.\\n')
`

/** A generator that always fails. */
const BROKEN = `console.error('cannot build the readme')
process.exit(1)
`

const GENERATED_README = '# Practice\n\nGenerated by the readme generator.\n'

const CHORES_CONFIG = {
    ...PRACTICE_ENGINE_CONFIG,
    generators: {
        readme: 'bun scripts/gen-readme.ts',
        broken: 'bun scripts/broken.ts',
    },
}

const CHORES_FILES = {
    'scripts/gen-readme.ts': GEN_README,
    'scripts/broken.ts': BROKEN,
}

const GenerateCheckSchema = z.object({
    name: z.literal('generate'),
    command: z.string(),
    ok: z.boolean(),
})

type GenerateCheck = z.infer<typeof GenerateCheckSchema>

/** Every `generate` check found anywhere in a value. */
const generateChecksIn = (value: unknown): GenerateCheck[] => {
    if (Array.isArray(value)) return value.flatMap(generateChecksIn)
    if (typeof value !== 'object' || value === null) return []
    const check = GenerateCheckSchema.safeParse(value)
    if (check.success) return [check.data]
    return Object.values(value).flatMap(generateChecksIn)
}

const generateChecks = (records: JournalRecord[]): GenerateCheck[] =>
    records.flatMap((record) => generateChecksIn(record.content))

let root = ''

beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'luca-engine-chores-'))
})

afterEach(async () => {
    await rm(root, { recursive: true, force: true })
})

describe('file modes a writer asks for (#618)', () => {
    test("the implementer's file_modes makes a file executable, and the committed file has the executable mode", async () => {
        const { testWriter, implementer, reviewer } = happyTurns()
        const practice = await createPracticeRepo({ root })
        const { action, tracker } = await practice.run({
            turns: [
                testWriter,
                {
                    ...implementer,
                    result: {
                        ...IMPLEMENTER_RESULT,
                        file_modes: [
                            { path: 'scripts/lint.ts', executable: true },
                        ],
                    },
                },
                reviewer,
            ],
        })

        expect(action).toMatchObject({ type: 'done', outcome: 'pr_opened' })
        const branch = tracker.pullRequests()[0]?.head ?? ''
        const entry = await git(
            practice.origin,
            'ls-tree',
            branch,
            'scripts/lint.ts'
        )
        expect(entry).toStartWith('100755 ')
    }, 90_000)

    test('a mode change on a path the test-writer may not write goes back to the test-writer, and the file keeps its mode', async () => {
        const { testWriter, implementer, reviewer } = happyTurns()
        const practice = await createPracticeRepo({ root })
        const { action, tracker, launches } = await practice.run({
            turns: [
                {
                    ...testWriter,
                    result: {
                        ...TEST_WRITER_RESULT,
                        file_modes: [{ path: 'README.md', executable: true }],
                    },
                },
                testWriter,
                implementer,
                reviewer,
            ],
        })

        expect(action).toMatchObject({ type: 'done', outcome: 'pr_opened' })
        const calls = launches.filter(({ ticket }) => ticket === 11)
        expect(calls.map(({ role }) => role)).toEqual([
            'test-writer',
            'test-writer',
            'implementer',
            'ticket-reviewer',
        ])
        expect(calls[1]?.prompt).toContain('README.md')
        const branch = tracker.pullRequests()[0]?.head ?? ''
        const entry = await git(practice.origin, 'ls-tree', branch, 'README.md')
        expect(entry).toStartWith('100644 ')
    }, 90_000)
})

describe('generators a writer asks for (#618)', () => {
    test('a named generator runs before the gates as a generate check, and its output is committed with the ticket', async () => {
        const { testWriter, implementer, reviewer } = happyTurns()
        const practice = await createPracticeRepo({
            root,
            config: CHORES_CONFIG,
            files: CHORES_FILES,
        })
        const { action, tracker, records } = await practice.run({
            turns: [
                testWriter,
                {
                    ...implementer,
                    result: {
                        ...IMPLEMENTER_RESULT,
                        run_generators: ['readme'],
                    },
                },
                reviewer,
            ],
        })

        expect(action).toMatchObject({ type: 'done', outcome: 'pr_opened' })
        expect(generateChecks(records)).toContainEqual({
            name: 'generate',
            command: 'bun scripts/gen-readme.ts',
            ok: true,
        })

        // It ran before the ticket's first gates.
        const generated = records.findIndex(
            (record) => generateChecksIn(record.content).length > 0
        )
        const gates = records.findIndex(
            (record) =>
                record.kind === 'gates_run' &&
                record.content.target === 'ticket'
        )
        expect(generated).toBeGreaterThanOrEqual(0)
        expect(generated).toBeLessThanOrEqual(gates)

        // Its output is in the ticket's green commit, and on the PR branch.
        const green = records.find(
            (record) =>
                record.kind === 'commit_made' &&
                record.ticket === 11 &&
                record.content.stage === 'green'
        )
        expect(
            green?.kind === 'commit_made' ? green.content.files : []
        ).toContain('README.md')
        const branch = tracker.pullRequests()[0]?.head ?? ''
        expect(await git(practice.origin, 'show', `${branch}:README.md`)).toBe(
            GENERATED_README
        )
    }, 90_000)

    test('an unknown generator name goes back to the implementer as a problem', async () => {
        const { testWriter, implementer, reviewer } = happyTurns()
        const practice = await createPracticeRepo({
            root,
            config: CHORES_CONFIG,
            files: CHORES_FILES,
        })
        const { action, launches } = await practice.run({
            turns: [
                testWriter,
                {
                    ...implementer,
                    result: {
                        ...IMPLEMENTER_RESULT,
                        run_generators: ['make-docs'],
                    },
                },
                implementer,
                reviewer,
            ],
        })

        expect(action).toMatchObject({ type: 'done', outcome: 'pr_opened' })
        const calls = launches.filter(
            ({ ticket, role }) => ticket === 11 && role === 'implementer'
        )
        expect(calls).toHaveLength(2)
        expect(calls[1]?.prompt).toContain('make-docs')
    }, 90_000)

    test('a failing generator is a failed generate check that goes back to the implementer', async () => {
        const { testWriter, implementer, reviewer } = happyTurns()
        const practice = await createPracticeRepo({
            root,
            config: CHORES_CONFIG,
            files: CHORES_FILES,
        })
        const { action, records, launches } = await practice.run({
            turns: [
                testWriter,
                {
                    ...implementer,
                    result: {
                        ...IMPLEMENTER_RESULT,
                        run_generators: ['broken'],
                    },
                },
                implementer,
                reviewer,
            ],
        })

        expect(action).toMatchObject({ type: 'done', outcome: 'pr_opened' })
        expect(generateChecks(records)).toContainEqual({
            name: 'generate',
            command: 'bun scripts/broken.ts',
            ok: false,
        })
        const calls = launches.filter(
            ({ ticket, role }) => ticket === 11 && role === 'implementer'
        )
        expect(calls).toHaveLength(2)
        expect(calls[1]?.prompt).toContain('broken')
    }, 90_000)
})
